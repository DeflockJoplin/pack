//! Flock camera OUI list + Axon OUI (from ESP32 `flock_detect.rs` / `axon_detect.rs`).

pub const AXON_OUI: [u8; 3] = [0x00, 0x25, 0xDF];

#[must_use]
pub fn is_axon_oui(mac: &[u8; 6]) -> bool {
    mac[0] == AXON_OUI[0] && mac[1] == AXON_OUI[1] && mac[2] == AXON_OUI[2]
}
